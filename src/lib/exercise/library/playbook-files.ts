// Reads the library playbook Markdown files and renders the generated module.
// Used by scripts/gen-library-playbooks.ts and by the sync test. Node only;
// the app reads playbooks.generated.ts instead.

import { readFileSync, readdirSync, statSync } from "node:fs";
import path from "node:path";

const LIBRARY_DIR = path.join("src", "lib", "exercise", "library");
export const GENERATED_PATH = path.join(LIBRARY_DIR, "playbooks.generated.ts");

/** Every playbook file as {relative path: text}, sorted by path. Paths use forward slashes. */
export function readPlaybookFiles(root = process.cwd()): Record<string, string> {
  const base = path.join(root, LIBRARY_DIR);
  const out: Record<string, string> = {};
  for (const collection of readdirSync(base).sort()) {
    const dir = path.join(base, collection, "playbooks");
    try {
      if (!statSync(dir).isDirectory()) continue;
    } catch {
      continue;
    }
    for (const name of readdirSync(dir).sort()) {
      if (!name.endsWith(".md")) continue;
      out[`${collection}/playbooks/${name}`] = readFileSync(path.join(dir, name), "utf8").replace(/\r\n?/g, "\n");
    }
  }
  return out;
}

export function renderPlaybookModule(files = readPlaybookFiles()): string {
  const lines = [
    "// Generated by scripts/gen-library-playbooks.ts from src/lib/exercise/library/*/playbooks/*.md.",
    "// Do not edit. Edit the Markdown file and run `npm run library:playbooks`.",
    "",
    "export const PLAYBOOK_FILES: Readonly<Record<string, string>> = {",
    ...Object.entries(files).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`),
    "};",
    "",
  ];
  return lines.join("\n");
}
