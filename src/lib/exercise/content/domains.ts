
// Scenario domains. Pickers branch off the selected domain so a mass layoff
// exercise does not offer NIST CSF as its framework. Domains apply to Crisis
// Sim and Strategic TTX. Non-cyber domains drop ATT&CK requirements.

export const SCENARIO_DOMAIN_KEYS = ["cyber", "legal", "financial", "people", "operational"] as const;
export type ScenarioDomainKey = (typeof SCENARIO_DOMAIN_KEYS)[number];

export interface ScenarioDomain {
  key: ScenarioDomainKey;
  label: string;
  description: string;
  /** Crisis types this domain authors against. */
  crisisTypes: readonly string[];
  /** Frameworks the team uses to structure its response. */
  frameworks: readonly string[];
  /** Compliance and regulatory tags that commonly apply. */
  complianceTags: readonly string[];
  /** Adversary archetypes for this domain. Cyber also uses THREAT_ACTORS. */
  adversaryProfiles: readonly string[];
  /** One line per crisis type, shown under the selected crisis. */
  crisisDescriptions: Readonly<Record<string, string>>;
  /** One line per adversary archetype, shown under the selected adversary. */
  adversaryDescriptions: Readonly<Record<string, string>>;
  /** Stakeholder groups relevant to this domain. */
  stakeholderGroups: readonly string[];
  /** Business impact axes relevant to this domain. */
  businessImpactFocus: readonly string[];
  /** Default adversary per crisis type, used until the author picks one. */
  defaultAdversaryByCrisis: Readonly<Record<string, string>>;
  /** True when ATT&CK techniques, kill chain, and technical artifacts apply. */
  showsCyberScaffolding: boolean;
}

